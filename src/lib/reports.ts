export type ReportSection = {
  title: string;
  rows: Array<[string, string]>;
};

export type ReportInput = {
  title: string;
  subtitle: string;
  sections: ReportSection[];
  shareText?: string;
  company?: {
    name?: string | null;
    address?: string | null;
    phone?: string | null;
    email?: string | null;
    logo_url?: string | null;
  } | null;
};

function escapeHtml(value: string) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

export function printReport(report: ReportInput) {
  // Keep the new window same-origin so we can render the report into it. Using
  // `noopener` here makes some browsers return a window whose document cannot
  // be written, which results in a blank tab.
  const printWindow = window.open("", "_blank");
  if (!printWindow) return false;

  const sections = report.sections
    .map(
      (section) => `
        <section>
          <h2>${escapeHtml(section.title)}</h2>
          <dl>${section.rows
            .map(
              ([label, value]) =>
                `<div><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value || "Not recorded")}</dd></div>`,
            )
            .join("")}</dl>
        </section>`,
    )
    .join("");
  const company = report.company;
  const companyName = company?.name?.trim() || "Mamakare";
  const companyContact = [company?.address, company?.phone, company?.email]
    .map((value) => value?.trim())
    .filter(Boolean)
    .join(" · ");
  const logoUrl = company?.logo_url?.trim() || `${window.location.origin}/icons/mamakare.svg`;

  printWindow.onload = () => {
    printWindow.setTimeout(() => printWindow.print(), 300);
  };
  printWindow.document.open();
  printWindow.document.write(`<!doctype html><html><head><title>${escapeHtml(report.title)}</title>
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <style>
      :root { color-scheme: light; font-family: Arial, sans-serif; color: #19333a; background: #fff; }
      body { margin: 0; padding: 40px; }
      main { max-width: 820px; margin: 0 auto; }
      header { display:flex; align-items:center; gap:14px; border-bottom:3px solid #087f7b; padding-bottom:20px; }
      header img { width:56px; height:56px; border-radius:14px; }
      .company-name { margin:0; color:#19333a; font-size:16px; font-weight:700; }
      .company-contact { margin:3px 0 10px; color:#66757f; font-size:11px; }
      h1 { margin:0; font-size:28px; color:#087f7b; }
      .subtitle { margin:5px 0 0; color:#66757f; font-size:14px; }
      section { margin-top:24px; border:1px solid #d9e5e5; border-radius:14px; padding:18px 20px; break-inside:avoid; }
      h2 { margin:0 0 12px; font-size:16px; color:#087f7b; }
      dl { margin:0; display:grid; gap:9px; }
      dl div { display:grid; grid-template-columns: 180px 1fr; gap:16px; border-bottom:1px solid #edf2f2; padding-bottom:7px; }
      dt { color:#66757f; font-size:12px; font-weight:700; text-transform:uppercase; letter-spacing:.06em; }
      dd { margin:0; font-size:14px; white-space:pre-wrap; }
      footer { margin-top:28px; color:#87979d; font-size:11px; text-align:center; }
      .actions { display:flex; justify-content:flex-end; margin-bottom:20px; }
      .print-button { border:0; border-radius:10px; background:#087f7b; color:#fff; padding:11px 16px; font-weight:700; cursor:pointer; }
      @media print { body { padding: 0; } section { border-color:#d9e5e5; } .actions { display:none; } }
    </style></head><body><main>
    <div class="actions"><button class="print-button" type="button" onclick="window.print()">Print / Save as PDF</button></div>
    <header><img src="${escapeHtml(logoUrl)}" alt="${escapeHtml(companyName)}" /><div><p class="company-name">${escapeHtml(companyName)}</p><p class="company-contact">${escapeHtml(companyContact)}</p><h1>${escapeHtml(report.title)}</h1><p class="subtitle">${escapeHtml(report.subtitle)}</p></div></header>
    ${sections}<footer>Generated by Mamakare · Secure care coordination</footer>
    </main></body></html>`);
  printWindow.document.close();
  return true;
}

export function shareReportOnWhatsApp(text: string) {
  const url = `https://wa.me/?text=${encodeURIComponent(text)}`;
  window.open(url, "_blank", "noopener,noreferrer");
}

function xmlEscape(value: string) {
  return escapeHtml(value).replaceAll("\n", "&#10;");
}

function wrapText(value: string, limit = 58) {
  const words = value.split(/\s+/);
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    if (!line) {
      line = word;
    } else if (`${line} ${word}`.length <= limit) {
      line += ` ${word}`;
    } else {
      lines.push(line);
      line = word;
    }
  }
  if (line) lines.push(line);
  return lines.length ? lines : ["Not recorded"];
}

async function reportImage(report: ReportInput) {
  const company = report.company;
  const companyName = company?.name?.trim() || "Mamakare";
  const contact = [company?.address, company?.phone, company?.email]
    .map((value) => value?.trim())
    .filter(Boolean)
    .join(" · ");
  const width = 1080;
  const padding = 64;
  const rowHeight = 34;
  const sectionGap = 26;
  let height = 250;
  const sectionMarkup: string[] = [];

  for (const section of report.sections) {
    const rows = section.rows.flatMap(([label, value]) => {
      const lines = wrapText(value || "Not recorded");
      return [{ label, lines }];
    });
    const sectionHeight =
      72 + rows.reduce((total, row) => total + Math.max(1, row.lines.length) * rowHeight, 0);
    const y = height;
    let rowOffset = 0;
    const rowMarkup = rows
      .map((row) => {
        const rowY = y + 62 + rowOffset * rowHeight;
        rowOffset += Math.max(1, row.lines.length);
        return `<text x="${padding + 22}" y="${rowY}" class="label">${xmlEscape(row.label)}</text><text x="${padding + 260}" y="${rowY}" class="value">${xmlEscape(row.lines.join(" "))}</text>`;
      })
      .join("");
    sectionMarkup.push(
      `<rect x="${padding}" y="${y}" width="${width - padding * 2}" height="${sectionHeight}" class="section" /><text x="${padding + 22}" y="${y + 38}" class="sectionTitle">${xmlEscape(section.title)}</text>${rowMarkup}`,
    );
    height += sectionHeight + sectionGap;
  }

  height += 70;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
    <rect width="100%" height="100%" fill="#ffffff" />
    <rect x="${padding}" y="${padding}" width="72" height="72" rx="18" fill="#087f7b" />
    <text x="${padding + 36}" y="${padding + 51}" text-anchor="middle" font-family="Arial,sans-serif" font-size="38" font-weight="700" fill="#ffffff">♥</text>
    <text x="${padding + 96}" y="${padding + 30}" class="company">${xmlEscape(companyName)}</text>
    <text x="${padding + 96}" y="${padding + 56}" class="contact">${xmlEscape(contact)}</text>
    <line x1="${padding}" y1="${padding + 104}" x2="${width - padding}" y2="${padding + 104}" stroke="#087f7b" stroke-width="5" />
    <text x="${padding}" y="${padding + 150}" class="title">${xmlEscape(report.title)}</text>
    <text x="${padding}" y="${padding + 180}" class="subtitle">${xmlEscape(report.subtitle)}</text>
    ${sectionMarkup.join("")}
    <text x="${width / 2}" y="${height - 26}" text-anchor="middle" class="footer">Generated by Mamakare · Secure care coordination</text>
    <style>
      .company { font: 700 30px Arial,sans-serif; fill: #19333a; }
      .contact { font: 16px Arial,sans-serif; fill: #66757f; }
      .title { font: 700 34px Arial,sans-serif; fill: #087f7b; }
      .subtitle { font: 18px Arial,sans-serif; fill: #66757f; }
      .section { fill: #ffffff; stroke: #d9e5e5; stroke-width: 2; }
      .sectionTitle { font: 700 21px Arial,sans-serif; fill: #087f7b; }
      .label { font: 700 14px Arial,sans-serif; fill: #66757f; }
      .value { font: 16px Arial,sans-serif; fill: #19333a; }
      .footer { font: 13px Arial,sans-serif; fill: #87979d; }
    </style>
  </svg>`;

  const svgBlob = new Blob([svg], { type: "image/svg+xml;charset=utf-8" });
  const svgUrl = URL.createObjectURL(svgBlob);
  try {
    const image = new Image();
    image.src = svgUrl;
    await image.decode();
    const canvas = document.createElement("canvas");
    canvas.width = width;
    canvas.height = height;
    const context = canvas.getContext("2d");
    if (!context) throw new Error("Unable to create report image");
    context.drawImage(image, 0, 0);
    return await new Promise<Blob>((resolve, reject) => {
      canvas.toBlob(
        (blob) => (blob ? resolve(blob) : reject(new Error("Unable to export report image"))),
        "image/png",
      );
    });
  } finally {
    URL.revokeObjectURL(svgUrl);
  }
}

export async function shareReportImage(report: ReportInput) {
  const blob = await reportImage(report);
  const file = new File([blob], `${report.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.png`, {
    type: "image/png",
  });
  if (navigator.share && navigator.canShare?.({ files: [file] })) {
    await navigator.share({ title: report.title, files: [file] });
    return "shared" as const;
  }

  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = file.name;
  link.click();
  URL.revokeObjectURL(url);
  return "downloaded" as const;
}
